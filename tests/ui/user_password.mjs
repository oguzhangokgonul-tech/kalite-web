import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5123';
const host = `firma-ui-preview.volkaportal.com:${new URL(base).port}`;
const output = '.tmp-ui-audit/user-password';
await fs.mkdir(output, { recursive: true });
const tenantBase = `http://${host}`;
const browser = await chromium.launch({ channel: 'chrome', args: ['--disable-gpu', '--no-proxy-server', '--host-resolver-rules=MAP firma-ui-preview.volkaportal.com 127.0.0.1'] });
async function loginWorks(username, password, expected) {
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto(tenantBase + '/login');
  await page.locator('#identity').fill(username);
  await page.locator('#password').fill(password);
  await page.locator('button[type="submit"]').click();
  await page.waitForLoadState('domcontentloaded');
  const status = await page.evaluate(async () => (await fetch('/session/csrf-token')).status);
  assert.equal(status, expected ? 200 : 401);
  await context.close();
}
try {
  for (const width of [390, 768, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 960 } });
    await context.request.get(base + '/__ui/login/super_admin');
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/users/new');
    const username = `password-browser-${width}`;
    const oldPassword = `Original-test-${width}`;
    const newPassword = `Changed-test-${width}`;
    await page.locator('#full_name').fill(`Password Browser ${width}`);
    await page.locator('#username').fill(username);
    await page.locator('#password').fill(oldPassword);
    await page.locator('.role-chip').filter({ hasText: 'Sadece' }).locator('input').check();
    await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
    await page.waitForURL(base + '/users');
    const row = page.locator('tbody tr').filter({ hasText: username });
    const edit = await row.locator('a[href$="/edit"]').getAttribute('href');
    await loginWorks(username, oldPassword, true);
    await page.goto(base + edit);
    assert.ok((await page.locator('#passwordPolicy').innerText()).includes('10'));
    await page.locator('#username').fill('preview-viewer');
    await page.locator('#password').fill(newPassword);
    await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
    await page.waitForLoadState('domcontentloaded');
    assert.ok(await page.locator('#usernameError').isVisible());
    assert.ok(await page.locator('#userFormError').isVisible());
    assert.equal(await page.locator('#username').getAttribute('aria-invalid'), 'true');
    assert.equal(await page.locator('#password').inputValue(), '');
    await page.locator('#username').fill(username);
    assert.ok(!(await page.locator('#usernameError').isVisible()));
    await page.locator('#password').fill('short');
    let posts = 0;
    page.on('request', request => { if (request.method() === 'POST') posts++; });
    await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
    assert.equal(posts, 0);
    assert.ok(await page.locator('#passwordError').isVisible());
    assert.ok(await page.locator('#userFormError').isVisible());
    assert.equal(await page.locator('#password').getAttribute('aria-invalid'), 'true');
    await page.waitForFunction(() => {
      const rect = document.getElementById('password').getBoundingClientRect();
      return rect.top >= 0 && rect.bottom <= innerHeight;
    });
    await page.screenshot({ path: `${output}/${width}-viewport.png` });
    await page.screenshot({ path: `${output}/${width}-validation.png`, fullPage: true });
    await page.locator('#password').fill(newPassword);
    await page.locator('#togglePassword').click();
    assert.equal(await page.locator('#password').getAttribute('type'), 'text');
    await page.locator('#togglePassword').click();
    assert.equal(await page.locator('#password').getAttribute('type'), 'password');
    await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
    await page.waitForURL(base + '/users');
    assert.ok((await page.locator('.alert-success').innerText()).includes('şifresi'));
    await loginWorks(username, oldPassword, false);
    await loginWorks(username, newPassword, true);
    await page.goto(base + edit);
    assert.equal(await page.locator('#password').inputValue(), '');
    await page.locator('#title').fill('Kalite Kontrol');
    await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
    await page.waitForURL(base + '/users');
    await loginWorks(username, newPassword, true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth), 0);
    page.once('dialog', dialog => dialog.accept());
    await page.locator('tbody tr').filter({ hasText: username }).getByRole('button', { name: 'Sil', exact: true }).click();
    await page.waitForLoadState('domcontentloaded');
    await loginWorks(username, newPassword, false);
    assert.deepEqual(errors, []);
    console.log('PASS', width, 'create/edit/password/blank-preserve/real-login/delete/validation/fit');
    await context.close();
  }
} finally { await browser.close(); }
